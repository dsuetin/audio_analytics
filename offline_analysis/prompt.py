def build_classification_user_prompt(
    store_id: str,
    seller_id: str | None,
    segment_text_with_times: str,
) -> str:
    return (
        "КОНТЕКСТ:\n"
        f"  store_id: {store_id}\n"
        f"  seller_id: {seller_id if seller_id else '(не определён)'}\n\n"
        "ТЕКСТ ОДНОГО РАЗГОВОРА (время | текст, ASR содержит ошибки и шум):\n"
        f"{segment_text_with_times}\n\n"
        "Ответь одним JSON-объектом."
    )


def format_segment_with_times(segment) -> str:
    """Форматирует rows сегмента для классификации: ``HH:MM:SS | text`` на строку."""
    lines = []
    for r in segment.rows:
        ts = r.created_at.strftime("%H:%M:%S")
        text = " ".join((r.text or "").split())
        lines.append(f"{ts} | {text}")
    return "\n".join(lines)


# Сохраняем старое имя для обратной совместимости (legacy).
def format_block_with_times(block) -> str:
    return format_segment_with_times(block)
