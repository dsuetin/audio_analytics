def build_long_dialog_resegment_prompt(
    store_id: str,
    rows: Sequence,
    is_very_long: bool = False,
    greet_count: int | None = None,
    end_count: int | None = None,
    forced: bool = False,
    greet_positions: "Sequence[int] | None" = None,
    end_positions: "Sequence[int] | None" = None,
) -> str:
    """Пользовательский prompt для дополнительного разделения длинного dialog-сегмента.

    ``rows`` — именно тот блок строк, который первичная сегментация оставила
    единым. Индексы ГЛОБАЛЬНЫЕ (Row.index), т.к. Segment.start_index/end_index
    тоже глобальные.

    ``greet_count`` / ``end_count`` — детерминированный счётчик приветствий
    и маркеров завершения (чек/оплата/прощание) в блоке. Выдаётся LLM-модели
    как ФАКТ, чтобы она не «забыла» маркеры (см. checkpoint §3.2). Для одного
    действительно длинного разговора счётчик ``greet_count == 1`` — LLM
    честно вернёт segments:[]. Для 2+ независимых приветствий счётчик
    ``greet_count >= 2`` — ЛЛМ ОБЯЗАНА начать искать границы.

    ``forced`` — сегмент попал на ре-сплит НЕ по длительности, а по
    force-trigger (например, ≥2 приветствия в блоке < 30 мин).

    ``greet_positions`` / ``end_positions`` — ГЛОБАЛЬНЫЕ индексы строк, где
    встретился каждый маркер (2026-09-03 iter.1). Конкретные индексы вместо
    абстрактных счётчиков — LLM-модели (qwen3.8:27b) легче принять решение,
    когда у неё под рукой конкретные строки для границы.
    """
    lines = []
    for r in rows:
        text = " ".join((r.text or "").split())
        lines.append(f"{r.index} | {r.created_at:%H:%M:%S} | {text}")
    body = "\n".join(lines)
    first = rows[0].index
    last = rows[-1].index
    duration_text = _fmt_duration(rows)
    emphasis = (
        "ЭТО ОЧЕНЬ ДЛИННЫЙ фрагмент — практически всегда внутри него несколько "
        "независимых клиентских взаимодействий. Оставь единым только тогда, "
        "когда это ОЧЕВИДНО ОДИН неразрывный разговор с одним клиентом.\n\n"
        if is_very_long else
        "ЭТО ДЛИННЫЙ фрагмент — может содержать один разговор, а может несколько "
        "последовательных клиентских взаимодействий. Разбей на блоки, если "
        "видишь явные границы (завершение+новое начало). Если это ОДНА "
        "непрерывная покупка с одним клиентом — оставь как есть (segments:[]).\n\n"
    )

    # --- Счётчик маркеров как ФАКТ (checkpoint §3.2) ---
    marks_facts: list[str] = []
    if greet_count is not None:
        marks_facts.append(
            f"  приветствий (здравствуйте/добрый день/добрый вечер): {greet_count}"
        )
    if end_count is not None:
        marks_facts.append(
            f"  завершений (чек/оплата/прощание/спасибо/бонусы): {end_count}"
        )
    # 2026-09-03 iter.1: конкретные индексы вместо только счётчика.
    pos_block = _positions_block(rows, greet_positions, end_positions)
    if pos_block:
        marks_facts.append("")
        marks_facts.append(pos_block.rstrip())
    if marks_facts:
        marks_block = (
            "FAKT (детерминированный счёт в блоке, выдан как данные, не как текст):\n"
            + "\n".join(marks_facts)
            + "\n"
        )
        if greet_count is not None and greet_count >= 2:
            marks_block += (
                f"  => {greet_count} независимых приветствий внутри ОДНОГО блока — "
                "это ОБЯЗАТЕЛЬНО 2+ взаимодействий клиентов. "
                "Каждое (кроме первого) приветствие, которое предшествует "
                "завершение предыдущего взаимодействия (чек/оплата/прощание), "
                "— ГРАНИЦА между блоками. "
                "Не верни segments:[]. "
                "Верни 2+ сегмента: [0..end_prev_block] и [start_new..last] "
                "для каждого последующего приветствия.\n"
            )
    else:
        marks_block = ""

    forced_note = (
        "ВНИМАНИЕ: этот фрагмент попал на ре-сплит НЕ по длительности, а по "
        "детерминированному маркеру (2+ приветствия внутри). Оставь единым "
        "segments:[] только если это РЕАЛЬНО один клиент, повторившийся "
        "внутрь разговора. Если приветствия относятся к разным клиентам — "
        "разбей на блоки.\n\n"
        if forced else ""
    )

    return (
        f"КОНТЕКСТ:\n"
        f"  store_id: {store_id}\n"
        f"  fragment_rows: {first}..{last} (всего {len(rows)} строк)\n"
        f"  fragment_duration: {duration_text}\n\n"
        f"{marks_block}"
        f"{forced_note}"
        f"Поток реплик (формат: index | HH:MM:SS | текст, ASR содержит ошибки и шум):\n"
        f"{body}\n\n"
        f"{emphasis}"
        f"Первичная сегментация объединила это в ОДИН dialog-сегмент. Раздели "
        f"на НЕПЕРЕКРЫВАЮЩИЕСЯ блоки по логическим границам (завершение одного "
        f"взаимодействия + новое начало другого) или верни segments:[] "
        f"если это ОДНО непрерывное взаимодействие с одним клиентом. "
        f"Ответь одним JSON-объектом."
    )


def _positions_block(
    rows: Sequence,
    greet_positions: "Sequence[int] | None",
    end_positions: "Sequence[int] | None",
) -> str:
    """Форматирует конкретные индексы/время маркеров (2026-09-03 iter.1).

    LLM-модели проще принять решение при конкретных строках/время вместо
    только численного счётчика (обучено: qwen3.8:27b стабильно ignores
    «greet_count=2» и возвращает segments:[]; с конкретными индексами
    LLM видит, что есть конкретный набор boundary-кандидатов).
    """
    out: list[str] = []
    index_to_time = {r.index: r.created_at for r in rows}

    def _fmt(pos: int) -> str:
        t = index_to_time.get(pos)
        return f"{pos} ({t:%H:%M:%S})" if t else f"{pos}"

    if greet_positions:
        out.append(
            f"  приветствия (позиции): {', '.join(_fmt(p) for p in greet_positions)}"
        )
    if end_positions:
        out.append(
            f"  завершения (позиции): {', '.join(_fmt(p) for p in end_positions)}"
        )
    return "\n".join(out) if out else ""


def _fmt_duration(rows: Sequence) -> str:
    """Человекочитаемая длительность фрагмента (минуты/часы)."""
    if not rows:
        return "0 мин"
    first = rows[0].created_at
    last = rows[-1].created_at
    delta = last - first
    total_min = delta.total_seconds() / 60.0
    hours = int(total_min // 60)
    mins = int(total_min % 60)
    if hours:
        return f"{hours}ч {mins:02d}мин"
    if total_min >= 1:
        return f"{total_min:.1f} мин"
    return f"{int(total_min*60)} сек"


